function encodeFont() {
  const count=256,width=5,height=7;
  const offsetTable=20, widthBlock=offsetTable+count*2;
  const heightBlock=widthBlock+count, dataBlock=heightBlock+count*2;
  const bitmap=Buffer.alloc(count*height*3);
  const out=Buffer.alloc(dataBlock+bitmap.length);
  out.writeUInt16LE(out.length,0);
  out[2]=0;out[3]=5;
  out.writeUInt16LE(16,4);
  out.writeUInt16LE(offsetTable,6);
  out.writeUInt16LE(widthBlock,8);
  out.writeUInt16LE(dataBlock,10);
  out.writeUInt16LE(heightBlock,12);
  out.writeUInt16LE(0x1012,14);
  out[17]=255;out[18]=height;out[19]=width;
  for(let c=0;c<count;c++){
    out.writeUInt16LE(dataBlock+c*height*3,offsetTable+c*2);
    out[widthBlock+c]=width;
    out.writeUInt16LE(height<<8,heightBlock+c*2);
    const ch=String.fromCharCode(c).toUpperCase();
    const rows=GLYPHS[ch]||GLYPHS["?"];
    for(let y=0;y<height;y++){
      for(let x=0;x<width;x++){
        if(rows[y][x]==="1"){
          const off=dataBlock+c*height*3+y*3+Math.floor(x/2);
          out[off]|=1<<(x%2?4:0);
        }
      }
    }
  }
  return out;
}
function verifyFont(blob) {
  if(blob[2]!==0||blob[3]!==5||blob[17]!==255)throw Error("Invalid font header");
  const widths=blob.readUInt16LE(8), heights=blob.readUInt16LE(12), offsets=blob.readUInt16LE(6);
  for(let i=0;i<256;i++){
    const off=blob.readUInt16LE(offsets+i*2);
    const height=blob.readUInt16LE(heights+i*2)>>8;
    if(!blob[widths+i]||off+height*Math.ceil(blob[widths+i]/2)>blob.length)
      throw Error("Font glyph out of bounds: "+i);
  }
  return true;
}

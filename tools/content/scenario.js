#!/usr/bin/env node
"use strict";
// CC0-1.0 original scenario generator for VanillaTD's normal 64x64 maps.
// Format: defines.h:1089 (1-byte TemplateType), map.cpp:1076-1165 and
// map.cpp:1206-1258 (1-byte template + 1-byte icon per logical map cell).
const fs=require("node:fs"),path=require("node:path");
const GRID=64,MAX=GRID*GRID;
const identifier=value=>{
  if(typeof value!=="string"||! /^[A-Za-z0-9_-]+$/.test(value))throw Error("Unsafe scenario identifier");
  return value;
};
function cell([x,y]){
  if(!Number.isInteger(x)||!Number.isInteger(y)||x<1||y<1||x>=63||y>=63)
    throw Error("Cell must lie in 1..62");
  return y*GRID+x;
}
function validate(input){
  if(!input||input.schema!==1||input.file!=="SCM94EA"||typeof input.name!=="string"||
     !/^[A-Za-z0-9 -]{1,40}$/.test(input.name))throw Error("Invalid scenario identity");
  if(!input.map||input.map.theater!=="TEMPERATE"||
     ![input.map.x,input.map.y,input.map.width,input.map.height].every(Number.isInteger)||
     input.map.x<1||input.map.y<1||input.map.width<1||input.map.height<1||
     input.map.x+input.map.width>63||input.map.y+input.map.height>63)
    throw Error("Invalid temperate map bounds");
  if(!input.terrain||![0,1].includes(input.terrain.fill)||!Array.isArray(input.terrain.cells))
    throw Error("Invalid terrain grid");
  if(!Array.isArray(input.waypoints)||input.waypoints.length<2||!Array.isArray(input.overlays)||
     !Array.isArray(input.trees)||!Array.isArray(input.units))throw Error("Invalid scenario features");
  input.terrain.cells.forEach(e=>{
    cell(e.at);
    if(![0,1].includes(e.template)||!Number.isInteger(e.icon)||e.icon<0||e.icon>255)
      throw Error("Invalid terrain template/icon");
  });
  for(const e of [...input.overlays,...input.trees]){
    cell(e.at);identifier(e.type);
  }
  input.waypoints.forEach((p,i)=>{cell(p);if(i>=8)throw Error("Waypoints limited to 8");});
  input.units.forEach(u=>{cell(u.at);identifier(u.house);identifier(u.type);});
  return input;
}
function generate(input){
  validate(input);
  const bin=Buffer.alloc(MAX*2);
  for(let i=0;i<MAX;i++)bin[i*2]=input.terrain.fill;
  for(const entry of input.terrain.cells){
    const i=cell(entry.at);bin[i*2]=entry.template;bin[i*2+1]=entry.icon;
  }
  const lines=[
    "; Original CC0-1.0 map generated by tools/content/scenario.js",
    "[Basic]",`Name=${input.name}`,"Intro=","Brief=","Win=","Lose=","Action=",
    "Player=GoodGuy","BuildLevel=98","",
    "[Map]",`Theater=${input.map.theater}`,`X=${input.map.x}`,`Y=${input.map.y}`,
    `Width=${input.map.width}`,`Height=${input.map.height}`,"",
    "[Waypoints]",...input.waypoints.map((p,i)=>`${i}=${cell(p)}`),"",
    "[GoodGuy]","Credits=50","",
    "[BadGuy]","Credits=50","",
    "[Overlay]",...input.overlays.map(e=>`${cell(e.at)}=${e.type}`),"",
    "[Terrain]",...input.trees.map(e=>`${cell(e.at)}=${e.type}`),"",
    "[Units]",...input.units.map((u,i)=>`${i.toString().padStart(3,"0")}=${u.house},${u.type},256,${cell(u.at)},0,Guard,None`),""
  ];
  return {ini:lines.join("\n"),bin};
}
function decodeBIN(bin){
  if(!Buffer.isBuffer(bin)||bin.length!==MAX*2)throw Error("Invalid map BIN size");
  return Array.from({length:MAX},(_,i)=>({template:bin[i*2],icon:bin[i*2+1]}));
}
function build(game,sourcePath=path.resolve(__dirname,"../../game/content/scenarios/foundry-test-range.json")){
  const data=JSON.parse(fs.readFileSync(sourcePath,"utf8"));
  const {ini,bin}=generate(data);
  const iniName=data.file+".INI",binName=data.file+".BIN";
  fs.writeFileSync(path.join(game,iniName),ini);
  fs.writeFileSync(path.join(game,binName),bin);
  return [iniName,binName];
}
if(require.main===module){
  if(process.argv.length!==4||process.argv[2]!=="build")throw Error("Usage: scenario.js build <gameDir>");
  build(process.argv[3]);
}
module.exports={generate,decodeBIN,build,cell};

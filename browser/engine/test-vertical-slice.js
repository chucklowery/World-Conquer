"use strict";
const assert=require("node:assert/strict");
const game=require("./vertical-slice");
const s=game.start();
assert.equal(s.phase,"playing");
assert.equal(s.units.filter(u=>u.team==="player").length,2);
assert.equal(game.inside(s,5,3),false);
assert.equal(game.inside(s,-1,0),false);
assert.equal(game.path(s,{x:1,y:2},{x:7,y:2},new Set()).some(p=>p.x===5&&p.y===2),false);
assert.equal(game.select(s,1,2),true);
assert.equal(game.select(s,7,2),true);
assert(s.units[0].path.length>0);
for(let i=0;i<12;i++)game.tick(s);
assert(s.frame===12);
assert(s.units[0].x!==1||s.units[0].y!==2);
// Isolated acceptance fixtures avoid conflating win flow with sentry damage.
const win=game.start();
win.units.filter(u=>u.team==="enemy").forEach(u=>u.hp=0);
win.units[0].x=7;win.units[0].y=2;
game.tick(win);
assert.equal(win.cargo,1);
win.units[0].x=15;win.units[0].y=4;
game.tick(win);
assert.equal(win.cargo,2);
win.units[0].x=16;win.units[0].y=8;
game.tick(win);
assert.equal(win.phase,"won");
game.tick(win);assert.equal(win.phase,"won");
const lost=game.start();
lost.units.filter(u=>u.team==="player").forEach(u=>u.hp=0);
game.tick(lost);assert.equal(lost.phase,"lost");
assert.equal(game.select(lost,1,2),false);
assert.deepEqual(game.path(s,{x:1,y:2},{x:5,y:3},new Set()),[]);
console.log("PASS: original tactical vertical slice, pathing, pickup, victory and defeat");
